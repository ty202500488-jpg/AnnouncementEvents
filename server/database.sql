-- ============================================================================
-- WMSU CAMPUS PORTAL (CRIMSON) - NORMALIZED 3NF POSTGRESQL SCHEMA
-- Compatible with PostgreSQL 14+ & DBeaver (Execute via Alt+X)
-- ============================================================================

BEGIN;

-- ============================================================================
-- 0. SHARED TRIGGER FUNCTION FOR AUTOMATIC updated_at TIMESTAMPS
-- ============================================================================
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ============================================================================
-- DOMAIN 1: IDENTITY, ACADEMIC STRUCTURE & VERIFICATION (6 TABLES)
-- ============================================================================

-- 1. ROLES
CREATE TABLE IF NOT EXISTS roles (
    role_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) UNIQUE NOT NULL,
    description TEXT
);

-- 2. DEPARTMENTS (17 WMSU Colleges)
CREATE TABLE IF NOT EXISTS departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_code VARCHAR(30) UNIQUE NOT NULL,
    department_name VARCHAR(150) UNIQUE NOT NULL,
    description TEXT,
    location VARCHAR(255),
    status VARCHAR(30) DEFAULT 'Active' NOT NULL CHECK (status IN ('Active', 'Inactive', 'Archived')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 3. PROGRAMS (58 WMSU Courses / Degree Programs)
CREATE TABLE IF NOT EXISTS programs (
    program_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id INTEGER NOT NULL REFERENCES departments(department_id) ON DELETE RESTRICT,
    program_name VARCHAR(150) NOT NULL,
    duration_years SMALLINT DEFAULT 4,
    description TEXT,
    status VARCHAR(30) DEFAULT 'Active' NOT NULL CHECK (status IN ('Active', 'Inactive', 'Archived')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_department_program UNIQUE (department_id, program_name)
);

-- 4. USERS (Core Identity & Authentication for Admin, Staff, and Students)
CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id INTEGER NOT NULL REFERENCES roles(role_id) ON DELETE RESTRICT,
    first_name VARCHAR(100) NOT NULL,
    middle_initial VARCHAR(10),
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    avatar_url TEXT,
    is_email_verified BOOLEAN DEFAULT FALSE NOT NULL,
    account_status VARCHAR(30) DEFAULT 'Active' NOT NULL
        CHECK (account_status IN ('Pending', 'Active', 'Suspended', 'Archived')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 5. STUDENT_PROFILES (1:1 Subtype Table for Student Academic & Verification Info)
CREATE TABLE IF NOT EXISTS student_profiles (
    user_id INTEGER PRIMARY KEY REFERENCES users(user_id) ON DELETE CASCADE,
    student_number VARCHAR(50) UNIQUE NOT NULL,
    department_id INTEGER NOT NULL REFERENCES departments(department_id) ON DELETE RESTRICT,
    program_id INTEGER REFERENCES programs(program_id) ON DELETE SET NULL,
    year_level VARCHAR(30) NOT NULL
        CHECK (year_level IN ('1st Year', '2nd Year', '3rd Year', '4th Year', '5th Year')),
    cor_image BYTEA,
    cor_mime_type VARCHAR(50),
    student_id_image BYTEA,
    student_id_mime_type VARCHAR(50),
    verification_status VARCHAR(30) DEFAULT 'Pending' NOT NULL
        CHECK (verification_status IN ('Unsubmitted', 'Pending', 'Verified', 'Rejected')),
    verified_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    verified_at TIMESTAMPTZ,
    verification_remarks TEXT,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

ALTER TABLE student_profiles
    DROP COLUMN IF EXISTS cor_url,
    DROP COLUMN IF EXISTS student_id_url,
    ADD COLUMN IF NOT EXISTS cor_image BYTEA,
    ADD COLUMN IF NOT EXISTS cor_mime_type VARCHAR(50),
    ADD COLUMN IF NOT EXISTS student_id_image BYTEA,
    ADD COLUMN IF NOT EXISTS student_id_mime_type VARCHAR(50);

-- 6. AUTH_TOKENS (Unified Email Confirmation & Password Reset Tokens)
CREATE TABLE IF NOT EXISTS auth_tokens (
    token_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_type VARCHAR(30) NOT NULL CHECK (token_type IN ('email_verification', 'password_reset')),
    token_hash VARCHAR(255) UNIQUE NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ============================================================================
-- DOMAIN 2: CAMPUS UNITS & PAGES (5 TABLES)
-- ============================================================================

-- 7. ORGANIZATIONS (Campus Offices like SAO & Student Organizations)
CREATE TABLE IF NOT EXISTS organizations (
    organization_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id INTEGER REFERENCES departments(department_id) ON DELETE SET NULL,
    org_code VARCHAR(30) UNIQUE NOT NULL,
    organization_name VARCHAR(150) UNIQUE NOT NULL,
    org_type VARCHAR(30) DEFAULT 'student_org' NOT NULL CHECK (org_type IN ('office', 'student_org')),
    description TEXT,
    status VARCHAR(30) DEFAULT 'Active' NOT NULL CHECK (status IN ('Active', 'Inactive', 'Archived')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 8. PAGES (Official Department, Office, or Organization Pages)
CREATE TABLE IF NOT EXISTS pages (
    page_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_name VARCHAR(150) NOT NULL,
    page_code VARCHAR(30) UNIQUE,
    page_description TEXT,
    page_type VARCHAR(30) DEFAULT 'department' NOT NULL
        CHECK (page_type IN ('department', 'organization', 'office')),
    department_id INTEGER UNIQUE REFERENCES departments(department_id) ON DELETE CASCADE,
    organization_id INTEGER UNIQUE REFERENCES organizations(organization_id) ON DELETE CASCADE,
    avatar_url TEXT,
    cover_url TEXT,
    contact_email VARCHAR(255),
    allow_event_registration BOOLEAN DEFAULT TRUE NOT NULL,
    created_by INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    status VARCHAR(30) DEFAULT 'Pending' NOT NULL
        CHECK (status IN ('Pending', 'Approved', 'Active', 'Rejected', 'Suspended', 'Archived')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_page_unit_exclusivity CHECK (
        NOT (department_id IS NOT NULL AND organization_id IS NOT NULL)
    )
);

-- 9. PAGE_MEMBERS (Staff & Editors Assigned to Manage a Page)
CREATE TABLE IF NOT EXISTS page_members (
    page_member_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id INTEGER NOT NULL REFERENCES pages(page_id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    role_on_page VARCHAR(50) DEFAULT 'Editor' NOT NULL
        CHECK (role_on_page IN ('Admin', 'Editor', 'page_admin', 'page_editor')),
    assigned_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    status VARCHAR(30) DEFAULT 'Active' NOT NULL CHECK (status IN ('Active', 'Revoked')),
    assigned_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_page_member_user UNIQUE (page_id, user_id)
);

-- 10. PAGE_REVIEWS (Admin Approval History for Pages)
CREATE TABLE IF NOT EXISTS page_reviews (
    review_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id INTEGER NOT NULL REFERENCES pages(page_id) ON DELETE CASCADE,
    reviewed_by INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    decision VARCHAR(30) NOT NULL CHECK (decision IN ('Approved', 'Rejected', 'Suspended')),
    remarks TEXT,
    reviewed_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 11. PAGE_FOLLOWS (Students/Staff Following Campus Pages)
CREATE TABLE IF NOT EXISTS page_follows (
    follow_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id INTEGER NOT NULL REFERENCES pages(page_id) ON DELETE CASCADE,
    follower_user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    followed_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_page_follower UNIQUE (page_id, follower_user_id)
);

-- ============================================================================
-- DOMAIN 3: UNIFIED POSTS, EVENTS & MODERATION (4 TABLES)
-- ============================================================================

-- 12. POST_CATEGORIES
CREATE TABLE IF NOT EXISTS post_categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) UNIQUE NOT NULL,
    description TEXT,
    created_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 13. POSTS (Unified Supertype Table for Both Announcements and Events)
CREATE TABLE IF NOT EXISTS posts (
    post_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id INTEGER NOT NULL REFERENCES pages(page_id) ON DELETE CASCADE,
    creator_user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    category_id INTEGER REFERENCES post_categories(category_id) ON DELETE SET NULL,
    post_type VARCHAR(20) NOT NULL CHECK (post_type IN ('announcement', 'event')),
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    image_url TEXT,
    audience VARCHAR(100) DEFAULT 'All Campus' NOT NULL,
    is_pinned BOOLEAN DEFAULT FALSE NOT NULL,
    is_urgent BOOLEAN DEFAULT FALSE NOT NULL,
    moderation_status VARCHAR(30) DEFAULT 'Approved' NOT NULL
        CHECK (moderation_status IN ('Pending', 'Approved', 'Rejected', 'Correction')),
    status VARCHAR(30) DEFAULT 'Published' NOT NULL
        CHECK (status IN ('Draft', 'Pending', 'Published', 'Upcoming', 'Ongoing', 'Completed', 'Cancelled', 'Rejected', 'Archived')),
    published_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ,
    is_archived BOOLEAN DEFAULT FALSE NOT NULL,
    archived_at TIMESTAMPTZ,
    archived_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    archive_reason VARCHAR(100),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 14. EVENT_DETAILS (1:1 Subtype Table for Posts where post_type = 'event')
CREATE TABLE IF NOT EXISTS event_details (
    post_id INTEGER PRIMARY KEY REFERENCES posts(post_id) ON DELETE CASCADE,
    event_date TIMESTAMPTZ NOT NULL,
    end_date TIMESTAMPTZ,
    location VARCHAR(255) NOT NULL,
    organizer_info TEXT,
    capacity INTEGER CHECK (capacity IS NULL OR capacity > 0),
    registration_deadline TIMESTAMPTZ,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 15. POST_MODERATION_LOGS (Admin Post Approval / Rejection / Correction Trail)
CREATE TABLE IF NOT EXISTS post_moderation_logs (
    moderation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id INTEGER NOT NULL REFERENCES posts(post_id) ON DELETE CASCADE,
    reviewer_user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    decision VARCHAR(30) NOT NULL CHECK (decision IN ('approve', 'reject', 'correction')),
    reason TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ============================================================================
-- DOMAIN 4: EVENT REGISTRATIONS & QR ATTENDANCE (5 TABLES)
-- ============================================================================

-- 16. EVENT_REGISTRATIONS
CREATE TABLE IF NOT EXISTS event_registrations (
    registration_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_post_id INTEGER NOT NULL REFERENCES event_details(post_id) ON DELETE CASCADE,
    registrant_user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    status VARCHAR(30) DEFAULT 'Registered' NOT NULL
        CHECK (status IN ('Registered', 'Attended', 'Cancelled')),
    registered_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    cancelled_at TIMESTAMPTZ,
    CONSTRAINT uq_event_registrant UNIQUE (event_post_id, registrant_user_id)
);

-- 17. EVENT_ATTENDANCE_SESSIONS (1:1 Open/Close Check-In Window per Event)
CREATE TABLE IF NOT EXISTS event_attendance_sessions (
    session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_post_id INTEGER UNIQUE NOT NULL REFERENCES event_details(post_id) ON DELETE CASCADE,
    status VARCHAR(20) DEFAULT 'CLOSED' NOT NULL CHECK (status IN ('OPEN', 'CLOSED')),
    open_time TIMESTAMPTZ,
    close_time TIMESTAMPTZ,
    opened_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 18. EVENT_QR_TOKENS (Rotating 30-Second SHA-256 QR Credentials)
CREATE TABLE IF NOT EXISTS event_qr_tokens (
    qr_token_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_post_id INTEGER NOT NULL REFERENCES event_details(post_id) ON DELETE CASCADE,
    token_hash VARCHAR(255) UNIQUE NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 19. EVENT_ATTENDANCE_RECORDS (1:1 with event_registrations — Strictly 3NF)
CREATE TABLE IF NOT EXISTS event_attendance_records (
    attendance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id INTEGER UNIQUE NOT NULL REFERENCES event_registrations(registration_id) ON DELETE CASCADE,
    status VARCHAR(20) DEFAULT 'NOT_MARKED' NOT NULL
        CHECK (status IN ('NOT_MARKED', 'PRESENT', 'ABSENT', 'EXCUSED')),
    checkin_time TIMESTAMPTZ,
    check_in_method VARCHAR(30) DEFAULT 'qr_scan' CHECK (check_in_method IN ('qr_scan', 'manual_staff')),
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 20. EVENT_ATTENDANCE_AUDITS (Audit Trail for QR Check-Ins & Manual Staff Corrections)
CREATE TABLE IF NOT EXISTS event_attendance_audits (
    attendance_audit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_id INTEGER NOT NULL REFERENCES event_attendance_records(attendance_id) ON DELETE CASCADE,
    actor_user_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    previous_status VARCHAR(20) NOT NULL,
    new_status VARCHAR(20) NOT NULL,
    source VARCHAR(20) NOT NULL CHECK (source IN ('student', 'staff', 'system')),
    reason TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ============================================================================
-- DOMAIN 5: NOTIFICATIONS, SYSTEM SETTINGS & AUDIT LOGS (4 TABLES)
-- ============================================================================

-- 21. NOTIFICATIONS
CREATE TABLE IF NOT EXISTS notifications (
    notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    actor_user_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    page_id INTEGER REFERENCES pages(page_id) ON DELETE CASCADE,
    post_id INTEGER REFERENCES posts(post_id) ON DELETE CASCADE,
    notification_scope VARCHAR(20) DEFAULT 'student' NOT NULL
        CHECK (notification_scope IN ('student', 'staff', 'mypage', 'admin')),
    type VARCHAR(50) DEFAULT 'general' NOT NULL,
    title VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN DEFAULT FALSE NOT NULL,
    read_at TIMESTAMPTZ,
    is_archived BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 22. ACADEMIC_YEARS
CREATE TABLE IF NOT EXISTS academic_years (
    academic_year_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_year SMALLINT NOT NULL,
    end_year SMALLINT NOT NULL,
    semester VARCHAR(50) NOT NULL CHECK (semester IN ('1st Semester', '2nd Semester', 'Summer')),
    is_active BOOLEAN DEFAULT FALSE NOT NULL,
    updated_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_academic_year_range CHECK (end_year = start_year + 1)
);

-- Enforce at most ONE active academic year at any time
CREATE UNIQUE INDEX IF NOT EXISTS uq_active_academic_year
    ON academic_years (is_active) WHERE is_active = TRUE;

-- 23. SYSTEM_SETTINGS (Normalized Key-Value Settings Store)
CREATE TABLE IF NOT EXISTS system_settings (
    setting_key VARCHAR(100) PRIMARY KEY,
    setting_value JSONB NOT NULL,
    category VARCHAR(50) DEFAULT 'general' NOT NULL,
    updated_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 24. AUDIT_LOGS (System-Wide Security & Operational Audit Trail)
CREATE TABLE IF NOT EXISTS audit_logs (
    log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    actor_role VARCHAR(50),
    action VARCHAR(150) NOT NULL,
    module VARCHAR(50) NOT NULL,
    target_type VARCHAR(50),
    target_id VARCHAR(100),
    outcome VARCHAR(20) DEFAULT 'SUCCESS' NOT NULL CHECK (outcome IN ('SUCCESS', 'FAILURE')),
    is_security_event BOOLEAN DEFAULT FALSE NOT NULL,
    ip_address VARCHAR(64),
    details JSONB,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ============================================================================
-- AUTOMATIC UPDATED_AT TRIGGERS
-- ============================================================================
DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_student_profiles_updated_at ON student_profiles;
CREATE TRIGGER trg_student_profiles_updated_at BEFORE UPDATE ON student_profiles FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_pages_updated_at ON pages;
CREATE TRIGGER trg_pages_updated_at BEFORE UPDATE ON pages FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_posts_updated_at ON posts;
CREATE TRIGGER trg_posts_updated_at BEFORE UPDATE ON posts FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_event_details_updated_at ON event_details;
CREATE TRIGGER trg_event_details_updated_at BEFORE UPDATE ON event_details FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_attendance_sessions_updated_at ON event_attendance_sessions;
CREATE TRIGGER trg_attendance_sessions_updated_at BEFORE UPDATE ON event_attendance_sessions FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_attendance_records_updated_at ON event_attendance_records;
CREATE TRIGGER trg_attendance_records_updated_at BEFORE UPDATE ON event_attendance_records FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ============================================================================
-- PERFORMANCE INDEXES
