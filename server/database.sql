CREATE INDEX IF NOT EXISTS idx_users_role_id ON users(role_id);
CREATE INDEX IF NOT EXISTS idx_student_profiles_dept ON student_profiles(department_id);
CREATE INDEX IF NOT EXISTS idx_student_profiles_verif ON student_profiles(verification_status);
CREATE INDEX IF NOT EXISTS idx_posts_page_type_status ON posts(page_id, post_type, status, is_archived);
CREATE INDEX IF NOT EXISTS idx_posts_moderation ON posts(moderation_status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_event_details_date ON event_details(event_date DESC);
CREATE INDEX IF NOT EXISTS idx_event_reg_event ON event_registrations(event_post_id);
CREATE INDEX IF NOT EXISTS idx_event_reg_user ON event_registrations(registrant_user_id);
CREATE INDEX IF NOT EXISTS idx_qr_tokens_lookup ON event_qr_tokens(token_hash, expires_at);
CREATE INDEX IF NOT EXISTS idx_notifications_recipient ON notifications(recipient_user_id, is_read, is_archived);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON audit_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_filters ON audit_logs(module, outcome, is_security_event);
CREATE INDEX IF NOT EXISTS idx_page_follows_follower ON page_follows(follower_user_id);

